// Turns docs/*.svg (the README's diagrams) into theme-aware SVG strings for the
// site: colours become CSS variables, so the same drawing reads in dark and
// light mode. Writes src/lib/figures.generated.ts. Runs before dev and build.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docs = join(here, "..", "..", "docs");
const NAMES = ["architecture", "sandbox-anatomy", "credential-flow", "cluster"];

// generator palette (docs/src/lib.py) -> site variables (globals.css --dg-*)
const MAP = {
  "#1f2328": "var(--color-fg)", "#57606a": "var(--color-fg-dim)", "#3d4652": "var(--dg-grey)",
  "#8a94a3": "var(--color-fg-mut)", "#9aa3ad": "var(--color-fg-mut)",
  "#c3c9d1": "var(--color-line-2)", "#d8dce1": "var(--color-line-2)",
  "#fff": "var(--dg-box)", "#fffffe": "var(--dg-area)", "#fefefe": "var(--dg-area)", "#ffffff": "none",
  "#f4f5f7": "var(--dg-vm)", "#f6f7f9": "var(--dg-ns)",
  "#76b900": "var(--color-nv)", "#4a7a00": "var(--dg-green-d)",
  "#f3f9e8": "var(--dg-green-t)", "#fbfdf7": "var(--dg-green-t)", "#b7dc7a": "var(--dg-green-l)",
  // namespace colours: frames keep their hue, tints and labels follow the theme
  "#8b5cf6": "#8b5cf6", "#f6f2ff": "var(--dg-ns-kc-t)", "#6d28d9": "var(--dg-ns-kc-l)",
  "#f59e0b": "#f59e0b", "#fff8eb": "var(--dg-ns-mon-t)", "#b45309": "var(--dg-ns-mon-l)",
  "#3b82f6": "#3b82f6", "#eff5ff": "var(--dg-ns-ll-t)", "#1d4ed8": "var(--dg-ns-ll-l)",
  "#14b8a6": "#14b8a6", "#edfcf9": "var(--dg-ns-cm-t)", "#0f766e": "var(--dg-ns-cm-l)",
  "#06b6d4": "#06b6d4", "#ecfdff": "var(--dg-ns-asb-t)", "#0e7490": "var(--dg-ns-asb-l)",
  "#ec4899": "#ec4899", "#fdf2f8": "var(--dg-ns-kyv-t)", "#be185d": "var(--dg-ns-kyv-l)",
  "#ef4444": "#ef4444", "#fef2f2": "var(--dg-ns-ag-t)", "#b91c1c": "var(--dg-ns-ag-l)",
  "#64748b": "#64748b", "#f5f7fa": "var(--dg-ns-demo-t)", "#475569": "var(--dg-ns-demo-l)",
  "#d62d2d": "var(--dg-red)", "#fdf0f0": "var(--dg-red-t)", "#fbdcdc": "var(--dg-red-t)",
};

const out = {};
for (const name of NAMES) {
  let s = readFileSync(join(docs, `${name}.svg`), "utf8");
  const [, w, h] = /viewBox="0 0 (\d+) (\d+)"/.exec(s);
  const title = /<title>([^<]*)<\/title>/.exec(s)?.[1] ?? name;
  s = s.replace(/<\?xml[^>]*>\s*/, "")
    .replace(/ width="\d+" height="\d+"/, "")
    .replace(/<svg /, `<svg class="dg-svg" `)
    // badge numbers: white text on green -> dark text on bright green
    .replace(/(<text[^>]*?)fill="#fff"/g, '$1fill="var(--dg-on)"')
    .replace(/(fill|stroke|color)="(#[0-9a-fA-F]{3,6})"/g, (m, attr, hex) => MAP[hex.toLowerCase()] ? `${attr}="${MAP[hex.toLowerCase()]}"` : m)
    .replace(/font-family="Inter,/g, `font-family="'Inter Variable', Inter,`)
    .replace(/font-family="ui-monospace,/g, `font-family="'JetBrains Mono', ui-monospace,`)
    // ids are shared by all figures on a page; prefix them per figure
    .replace(/id="([^"]+)"/g, `id="${name}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`)
    .replace(/href="#([^"]+)"/g, `href="#${name}-$1"`);
  out[name] = { title, w: +w, h: +h, svg: s.trim() };
}
// the generator's icon set, for the diagrams drawn by components (LiveDiagram)
const iconSrc = readFileSync(join(docs, "src", "symbols.txt"), "utf8") + readFileSync(join(docs, "src", "lib.py"), "utf8");
const icons = {};
for (const m of iconSrc.matchAll(/<symbol id="(i-[a-z-]+)"[^>]*>(.*?)<\/symbol>/g)) icons[m[1]] = m[2];
writeFileSync(join(here, "..", "src", "lib", "icons.generated.ts"),
  "// Generated by scripts/build-figures.mjs from docs/src. Do not edit.\n" +
  `export const ICONS: Record<string, string> = ${JSON.stringify(icons)};\n`);
console.log("icons:", Object.keys(icons).length);

writeFileSync(join(here, "..", "src", "lib", "figures.generated.ts"),
  "// Generated by scripts/build-figures.mjs from docs/*.svg. Do not edit.\n" +
  `export const FIGURE_SVG: Record<string, { title: string; w: number; h: number; svg: string }> = ${JSON.stringify(out)};\n`);
console.log("figures:", NAMES.join(", "));

// The manifests the lessons walk through line by line (<YamlRead>): copied
// verbatim into src/lib/yaml-files.generated.ts, so the page always shows the
// file the learner applies.
const YAML_FILES = [
  "manifests/agents/pi-agent.yaml",
  "manifests/policies/pi-agent.yaml",
  "manifests/openclaw/policies/skills-locked.policy.yaml",
  "manifests/tools/sre-tools.yaml",
  "manifests/policies/mcp-agent.yaml",
  "manifests/policies/tools-agent.yaml",
];
const repo = join(here, "..", "..");
const yamlOut = Object.fromEntries(YAML_FILES.map((f) => [f, readFileSync(join(repo, f), "utf8").replace(/\n+$/, "")]));
writeFileSync(join(here, "..", "src", "lib", "yaml-files.generated.ts"),
  "// Generated by scripts/build-figures.mjs from the repo's manifests. Do not edit.\n" +
  `export const YAML_FILES: Record<string, string> = ${JSON.stringify(yamlOut, null, 2)};\n`);
console.log(`yaml files: ${YAML_FILES.length}`);
